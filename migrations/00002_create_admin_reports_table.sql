CREATE TYPE report_reason AS ENUM (
    'SPAM',
    'HARASSMENT',
    'INAPPROPRIATE_CONTENT',
    'FRAUD',
    'PRIVACY_VIOLATION',
    'OTHER'
);

CREATE TABLE admin_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_user_id BIGINT,
    reported_user_id BIGINT,
    reported_group_id BIGINT,
    reason report_reason NOT NULL,
    description TEXT,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    reviewed_by_user_id BIGINT,
    response TEXT,
    resolved_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMPTZ,

    CONSTRAINT fk_admin_reports_reporter_user
        FOREIGN KEY (reporter_user_id) REFERENCES users(id)
        ON UPDATE CASCADE ON DELETE SET NULL,

    CONSTRAINT fk_admin_reports_reported_user
        FOREIGN KEY (reported_user_id) REFERENCES users(id)
        ON UPDATE CASCADE ON DELETE SET NULL,

    CONSTRAINT fk_admin_reports_reviewed_by_user
        FOREIGN KEY (reviewed_by_user_id) REFERENCES users(id)
        ON UPDATE CASCADE ON DELETE SET NULL
);

-- Indexes for performance and filtering
CREATE INDEX idx_admin_reports_reporter_user_id ON admin_reports (reporter_user_id);
CREATE INDEX idx_admin_reports_reported_user_id ON admin_reports (reported_user_id);
CREATE INDEX idx_admin_reports_reported_group_id ON admin_reports (reported_group_id);
CREATE INDEX idx_admin_reports_status ON admin_reports (status);
CREATE INDEX idx_admin_reports_reason ON admin_reports (reason);
CREATE INDEX idx_admin_reports_created_at ON admin_reports (created_at DESC);
CREATE INDEX idx_admin_reports_deleted_at ON admin_reports (deleted_at);

