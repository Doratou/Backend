CREATE TABLE wallet_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users (id),
    type VARCHAR(12) NOT NULL CHECK (type IN ('PURCHASE', 'SPEND', 'REWARD')),
    status VARCHAR(12) NOT NULL CHECK (status IN ('SUCCEEDED', 'FAILED')),
    description TEXT NOT NULL,
    token_amount BIGINT NOT NULL CHECK (token_amount > 0),
    balance_after BIGINT NOT NULL CHECK (balance_after >= 0),
    amount_toman BIGINT CHECK (amount_toman > 0),
    base_unit_price_toman BIGINT CHECK (base_unit_price_toman > 0),
    discount_percent SMALLINT NOT NULL DEFAULT 0 CHECK (discount_percent BETWEEN 0 AND 99),
    package_id VARCHAR(32),
    idempotency_key VARCHAR(128),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT wallet_transactions_purchase_fields CHECK (
        (type = 'PURCHASE' AND amount_toman IS NOT NULL AND base_unit_price_toman IS NOT NULL
            AND idempotency_key IS NOT NULL AND length(idempotency_key) > 0)
        OR (type IN ('SPEND', 'REWARD') AND status = 'SUCCEEDED'
            AND amount_toman IS NULL AND base_unit_price_toman IS NULL
            AND package_id IS NULL AND discount_percent = 0)
    ),
    CONSTRAINT wallet_transactions_user_idempotency_key UNIQUE (user_id, idempotency_key)
);

CREATE INDEX wallet_transactions_user_created_idx ON wallet_transactions (user_id, created_at DESC, id DESC);
CREATE INDEX wallet_transactions_user_type_created_idx ON wallet_transactions (user_id, type, created_at DESC, id DESC);

