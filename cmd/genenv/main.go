package main

import (
	"bufio"
	"fmt"
	"log"
	"os"
	"strings"
)

func main() {
	envFile := ".env"
	if _, err := os.Stat(envFile); os.IsNotExist(err) {
		envFile = ".env.example"
	}

	file, err := os.Open(envFile)
	if err != nil {
		log.Fatalf("failed to open %s: %v", envFile, err)
	}
	defer file.Close()

	var keys []string
	seen := make(map[string]bool)

	scanner := bufio.NewScanner(file)
	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		parts := strings.SplitN(line, "=", 2)
		if len(parts) > 0 {
			key := strings.TrimSpace(parts[0])
			if key != "" && !seen[key] {
				seen[key] = true
				keys = append(keys, key)
			}
		}
	}

	if err := scanner.Err(); err != nil {
		log.Fatalf("error reading %s: %v", envFile, err)
	}

	var sb strings.Builder
	sb.WriteString("// Code generated by cmd/genenv; DO NOT EDIT.\n\n")
	sb.WriteString("package bootstrap\n\n")
	sb.WriteString("// EnvKeys contains all environment variable keys extracted from .env\n")
	sb.WriteString("var EnvKeys = []string{\n")
	for _, k := range keys {
		sb.WriteString(fmt.Sprintf("\t%q,\n", k))
	}
	sb.WriteString("}\n")

	targetPath := "bootstrap/gen_envkeys.go"
	if err := os.WriteFile(targetPath, []byte(sb.String()), 0644); err != nil {
		log.Fatalf("failed to write %s: %v", targetPath, err)
	}

	fmt.Printf("Successfully generated %s with %d keys from %s\n", targetPath, len(keys), envFile)
}
